"""Generate docs/COMMANDS.md and docs/SETTINGS.md from the live registries (so docs never drift).

    python tools/gen_docs.py
"""
import os, sys, tempfile
sys.path.insert(0, ".")
os.environ.setdefault("DB_PATH", os.path.join(tempfile.mkdtemp(), "x.db"))
os.environ.setdefault("BOT_TOKEN", "1:x")

from guardbot import config, database
database.init()
from guardbot.app import build_application
build_application("123456:TESTTOKENTESTTOKENTESTTOKENTESTTOKEN12")
from guardbot.core.registry import COMMANDS, HELP, PRIVATE_ONLY
from guardbot.settings_schema import MENUS

LEGEND = {"👑": "Founder / co-founder", "👮🏻": "Admin", "👷🏻": "Moderator", "👥": "Everyone", "🔰": "Pro (free here)",
          "🛠": "Bot developer"}
groups: dict[str, dict] = {}
seen_fn = {}
for name, fn in sorted(COMMANDS.items()):
    seen_fn.setdefault(fn, []).append(name)
rows = []
for fn, names in seen_fn.items():
    role, desc = HELP.get(names[0], ("👥", ""))
    rows.append((role, names, desc, any(n in PRIVATE_ONLY for n in names), fn.__module__.rsplit(".", 1)[-1]))
rows.sort(key=lambda r: (r[4], r[1][0]))

out = ["# Command reference", "",
       "_Generated by `tools/gen_docs.py` from the code - %d commands (%d names incl. aliases)._" % (len(rows), len(COMMANDS)), "",
       "Every command works with any of the prefixes `/ ! . ;` (e.g. `/ban`, `!ban`, `;ban`). "
       "Identify users by **reply**, **@username**, **numeric ID**, **t.me link** or **mention**.", "",
       "Durations accept `s m h d w M y` or words: `/ban @user 3d 2h 4m reason`, `/mute @user 30 minutes`.", "",
       "Legend: " + " · ".join(f"{k} {v}" for k, v in LEGEND.items()), ""]
cur = None
for role, names, desc, priv, mod in rows:
    if mod != cur:
        cur = mod
        out += [f"## {mod}", "", "| Command | Who | Notes |", "|---|---|---|"]
    out.append("| " + " ".join(f"`/{n}`" for n in names) + f" | {role} | {desc}{' (private chat)' if priv else ''} |")
    if rows[-1][4] != mod and False:
        out.append("")
open("docs/COMMANDS.md", "w", encoding="utf-8").write("\n".join(out) + "\n")

# settings tree: rendered from the real menu engine (what a user sees), following every sub-menu once
from guardbot.handlers import menu as _menu
database.get().ensure_chat(-1001, "Example group", "supergroup", 1)
lines = ["# Settings menu map", "", "_Generated by rendering every menu with the real engine. Open with `/settings` (answers with an "
         "'Open in Private Chat' button) or `/start cfg<chat id without the minus>` in private._", ""]
seen = set()


def walk(mid, depth):
    if mid in seen:
        return
    seen.add(mid)
    text, kb = _menu.build(-1001, mid)
    title = text.split("\n")[0].replace("<b>", "").replace("</b>", "")[:70]
    lines.append("  " * depth + f"- **{title}**  (`{mid}`)")
    for row in kb.inline_keyboard:
        lines.append("  " * (depth + 1) + "- " + "  |  ".join(b.text.replace("\n", " ") for b in row))
    for row in kb.inline_keyboard:
        for b in row:
            cb = b.callback_data or ""
            if cb.startswith("m|"):
                nxt = cb.split("|", 2)[2]
                if nxt not in seen and not nxt.startswith(("pad:", "msg:")):
                    walk(nxt, depth + 1)


walk("main", 0)
open("docs/SETTINGS.md", "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("docs generated:", len(rows), "commands,", len(seen), "menus")
